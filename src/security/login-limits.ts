/**
 * src/security/login-limits.ts — 콘솔 로그인·가입 **코드 상한의 한 곳**(2026-10-10 잠금 DoS 수정 — 런북 deploy §48 · ADR-0006).
 *
 * 문제였던 것: 링크 로그인을 없애자(2026-10-10) "코드 예산이 끝나도 링크는 된다" 는 탈출구가 사라졌다. 계정당 하루 틀린 코드 예산(20)은
 * **모든 IP 의 틀린 코드**를 합쳐 셌으므로, 공격자가 피해자 주소로 코드를 요청해 자기 브라우저에서 틀린 코드를 넣으면 피해자가 24시간 로그인하지
 * 못했다. 고침 — 업계 관례대로 **실패는 코드와 IP 에만 묶고, 주소에는 발급만 묶는다**:
 *
 *   ① 코드당: 틀린 코드 5회면 그 코드는 끝(새로 요청하면 된다). 코드는 요청한 브라우저의 논스에 묶여 있어 남의 코드를 태울 수 없다.
 *   ② IP 당(소스 IP 의 HMAC — IPv6 는 /64): 발급 요청 시간당 10회 · 틀린 코드 시간당 30회. 넘으면 429 — 주소와 무관하다(열거 신호가 아니다).
 *   ③ 주소(사용자)당: **발급만**. (주소, IP) 시간당 3통은 언제나. 그 위는 요청자가 신뢰 IP 인지로 갈린다 — 신뢰 IP = 이 주소로 지난 30일 안에
 *      로그인에 성공한 요청자 키. 신뢰 IP 는 넉넉하게(그 주소의 모든 코드로 15분 5통 · 하루 50통), 그 밖의 IP 는 **신뢰 밖으로 나간 코드만** 세어
 *      15분 2통 · 하루 4통. 넘으면 조용히 적지 않는다(응답은 같은 202). 공격자가 신뢰 밖의 몫을 다 써도 피해자의 평소 IP 는 코드를 받는다.
 *   ④ 실패로 생기는 **주소 단위 잠금은 없다** — 다른 IP 의 실패는 이 IP 의 로그인을 막지 못한다.
 *
 * 무차별 대입의 바닥: 신뢰 밖에서 주소당 하루 코드 4통 × 코드당 5회 = **20번** → 하루 성공 확률 ≤ 2 × 10^-5(키 회전 중에는 2배). 가입 코드도
 * 주소당 하루 4통 × 5회 = 20번. 신뢰 IP 는 이미 그 주소로 로그인한 쪽이라 이 바닥에 넣지 않는다.
 * 남는 틈: 처음 보는 기기 · IP 의 로그인은 여러 IP 의 공격자가 신뢰 밖 몫(하루 4통)을 채우는 동안 최대 하루 미뤄질 수 있다 — 그때의 길은 신뢰 IP 에서
 * 로그인하거나 운영자 재설정이다.
 * 그 밖의 층(그대로): 로그인 메일러의 사용자당 시간당 10통(`OWNER_LOGIN_NOTIFY_HOURLY_CAP_PER_USER`) · API 스로틀 · admin λ 예약 동시성.
 *
 * 이 파일은 상수뿐이다(DB 도 로그도 없다). 숫자를 바꾸면 런북 deploy §48 · ADR-0006 의 표도 같은 커밋에서 고친다.
 */

// ---------------------------------------------------------------------------
// ① 코드당
// ---------------------------------------------------------------------------

/** 한 코드(로그인 시도 = `owner_login_links`/`signup_links` 행 하나)에서 틀릴 수 있는 횟수. 이만큼 틀리면 그 코드는 끝이다. */
export const LOGIN_CODE_MAX_FAILURES = 5;

// ---------------------------------------------------------------------------
// ② IP 당
// ---------------------------------------------------------------------------

/** IP 당 로그인 코드 발급 요청(로그인 요청 · 초대 claim — 원장 `owner_login_requests`) 상한 — 창 1시간에 10회. 넘으면 429(주소와 무관). */
export const LOGIN_REQUESTS_PER_CLIENT = 10;
export const LOGIN_REQUEST_WINDOW_MS = 60 * 60 * 1000;

/**
 * IP 당 틀린 코드(로그인·가입 합산 — 원장 `login_code_attempts`, 한 행 = 틀린 코드 하나) 상한 — 창 1시간에 30회. 넘으면 그 IP 의 코드 verify 는
 * 429(주소와 무관). 맞는 코드는 세지 않는다 — 한 출구 IP 뒤의 여러 사람이 각자 로그인하는 것은 막히지 않는다.
 */
export const LOGIN_CODE_FAILURES_PER_CLIENT = 30;
export const LOGIN_CODE_FAILURE_WINDOW_MS = 60 * 60 * 1000;

/** IP 당 가입 요청 상한 — 시간당 5회. 넘으면 429(주소와 무관). */
export const SIGNUP_REQUESTS_PER_CLIENT_PER_HOUR = 5;

// ---------------------------------------------------------------------------
// ③ 주소(사용자)당 — 발급만
// ---------------------------------------------------------------------------

/** (사용자, IP)당 시간당 로그인 코드 상한. 넘으면 조용히 적지 않는다(응답은 같은 202). 성공한 적 있는 IP 에도 걸린다. */
export const LOGIN_LINKS_PER_CLIENT_PER_USER_PER_HOUR = 3;
/** 신뢰 IP 의 주소당 짧은 창 상한 — 그 주소의 모든 코드로 15분 5통. 넘으면 조용히 적지 않는다. */
export const LOGIN_LINKS_PER_USER_PER_WINDOW = 5;
export const LOGIN_LINK_USER_WINDOW_MS = 15 * 60 * 1000;
/** 신뢰 IP 의 주소당 하루 천장 — 그 주소의 모든 코드로 50통(메일 폭탄의 바닥). */
export const LOGIN_LINKS_PER_USER_PER_DAY = 50;
/** 신뢰 밖 IP 의 주소당 짧은 창 상한 — 신뢰 밖으로 나간 코드만 세어 15분 2통. */
export const LOGIN_UNTRUSTED_LINKS_PER_USER_PER_WINDOW = 2;
/** 신뢰 밖 IP 의 주소당 하루 상한 — 신뢰 밖으로 나간 코드만 세어 4통(× 코드당 5회 = 하루 20번). */
export const LOGIN_UNTRUSTED_LINKS_PER_USER_PER_DAY = 4;
/** 이 주소로 로그인에 성공한 적이 있는 IP(같은 요청자 키의 `used_at` 있는 행)를 믿는 기간 — 30일. */
export const LOGIN_TRUSTED_REQUESTER_DAYS = 30;

/** (같은 주소, 같은 IP)의 하루 가입 요청 상한 — 넘으면 **조용히** 링크를 적지 않는다(응답은 같은 202). */
export const SIGNUP_REQUESTS_PER_EMAIL_PER_CLIENT_PER_DAY = 3;
/** 같은 주소의 하루 가입 요청 상한(IP 무관 — 가입 · 대기자 명단 원장) — 메일 폭탄의 바닥. 넘으면 **조용히** 적지 않는다. */
export const SIGNUP_REQUESTS_PER_EMAIL_PER_DAY = 10;
/** 같은 주소의 하루 **가입 코드**(`signup_links`) 상한 — 4통 × 5회 = 하루 20번(로그인의 신뢰 밖 바닥과 같다). 넘으면 조용히 적지 않는다. */
export const SIGNUP_LINKS_PER_EMAIL_PER_DAY = 4;

-- ---------------------------------------------------------------------------
-- messages.status 에 'denied' 를 추가한다 (§4.5-1 위반 수정, P1b 리뷰 MAJOR 3)
-- ---------------------------------------------------------------------------
--
-- 왜 필요한가:
--   정책이 막은 시도는 lease 를 한 번도 잡지 못하고 `pending` 으로 **영구히** 남았다.
--   스위퍼도 없고 status 에 그것을 표현할 값도 없었다 — 즉 "정책이 막았다" 를
--   `messages` 가 말할 방법이 없었다. 그 결과가 계약 모순이다:
--     최초 호출 → 403 policy_denied
--     같은 키 재호출 → 202 ("아직 발송되지 않았다")
--   §4.5-1 은 *"동일 키 재호출은 최초 결과를 그대로 반환"* 이라고 쓴다. 403 과 202 는
--   같지 않고, 더 나쁜 것은 202 를 받은 클라이언트가 **영원히 나가지 않을 메일을
--   기다린다**는 것이다.
--
-- 왜 'failed' 로 때우지 않는가:
--   'failed' 는 "보내려 했는데 전송이 실패했다" 는 뜻이고, `ses-event-consumer`·운영
--   조회·AC-9 가 전부 그 뜻에 기대고 있다. 정책 거부를 거기에 섞으면 이 프로젝트가
--   구별하려는 두 사건("막았다" vs "나가다 실패했다")이 한 값이 된다.
--
-- **왜 파일이 둘로 나뉘는가 (다음 파일과 함께 읽어라):**
--   `ALTER TYPE ... ADD VALUE` 로 추가한 enum 값은 **같은 트랜잭션 안에서 사용할 수 없다**
--   (Postgres 제약). 이 러너는 파일 하나를 트랜잭션 하나로 돌리므로(`src/db/migrate.ts`),
--   값 추가와 그 값을 쓰는 제약 변경은 반드시 다른 파일이어야 한다. 한 파일로 합치면
--   `unsafe use of new value of enum type` 으로 죽는다.

ALTER TYPE message_status ADD VALUE IF NOT EXISTS 'denied';

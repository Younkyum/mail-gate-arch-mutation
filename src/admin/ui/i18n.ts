/**
 * src/admin/ui/i18n.ts — 콘솔 화면의 두 언어(`signup-contract.md` §8: 한국어 기본 · 영어).
 *
 * **원문은 한국어다.** 페이지 모듈(`login.ts`·`signup.ts`·`app.ts`)은 지금처럼 한국어로 적고, 영어 벌은 이 파일의 사전이
 * **모듈 로드 때** 만든다(`buildPage(parts, lang)` — 언어마다 HTML·스크립트가 다르므로 스크립트 자산·CSP 도 언어마다 따로다).
 * 사전의 키는 원문 조각 그대로다(마크업의 글 조각 · 스크립트 문자열 안의 조각). 그래서:
 *   - 한국어 원문이 바뀌면 그 키가 사전에 없어지고, 영어 페이지에 한글이 남아 테스트가 빨개진다(`admin-ui.test.ts` —
 *     영어 페이지의 한글은 언어 전환 링크 "한국어" 하나뿐이어야 한다). 쓰이지 않는 키(긴 키에 가려져 한 번도 바뀌지 않는 키 포함)도 빨갛다(`admin-i18n.test.ts` ⓘ-3).
 *   - `MESSAGES.ko`·`MESSAGES.en` 의 키 집합은 같다(ko 는 원문 → 원문).
 * 번역은 **긴 키부터** 바꾼다(짧은 키가 긴 조각의 일부일 때 긴 것이 먼저). 문맥마다 이스케이프가 다르다: 마크업은 HTML
 * 텍스트, 스크립트는 JS 문자열 리터럴 안. 영어 문구는 제품 영어로 쓴다(직역하지 않는다).
 *
 * API 는 코드만 돌려주고(서버의 `detail` 은 한국어다), 화면 문구는 페이지 언어의 사전 문구다 — 영어 화면은 서버 `detail` 을
 * 덧붙이지 않는다(`app.ts` `human`).
 */

export type Lang = 'ko' | 'en';
export const LANGS: readonly Lang[] = ['ko', 'en'];
export const DEFAULT_LANG: Lang = 'ko';

export function isLang(value: unknown): value is Lang {
  return value === 'ko' || value === 'en';
}

/**
 * 언어 선택(계약 §8): ① 쿼리 `?lang=ko|en`(라우트가 쿠키를 적고 302 한다 — 여기서는 값만) ② 쿠키 `__Host-atmark_lang`
 * ③ `Accept-Language` 의 **첫 언어**가 `en` 으로 시작하면 영어, 아니면 한국어.
 */
export function selectLang(input: { readonly query?: string | undefined; readonly cookie?: string | undefined; readonly acceptLanguage?: string | undefined }): Lang {
  if (isLang(input.query)) return input.query;
  if (isLang(input.cookie)) return input.cookie;
  const first = (input.acceptLanguage ?? '').split(',')[0]?.split(';')[0]?.trim().toLowerCase() ?? '';
  return first.startsWith('en') ? 'en' : DEFAULT_LANG;
}


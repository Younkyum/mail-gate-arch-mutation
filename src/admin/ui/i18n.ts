/** 긴 키부터 — 짧은 키가 긴 조각 안에 있을 때 긴 조각이 먼저 통째로 바뀐다. */
const KEYS_LONGEST_FIRST = Object.keys(EN).sort((a, b) => b.length - a.length || (a < b ? -1 : 1));

function escapeHtml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function escapeJs(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, '\\n');
}

/**
 * 원문 → 그 언어. 한국어는 그대로. 영어는 사전의 키를 긴 것부터 바꾼다. **사전에 없는 조각은 한글로 남는다** — 그것을
 * 테스트가 잡는다(조용히 빠진 번역이 운영에 나가지 않게).
 */
export function localize(source: string, lang: Lang, context: 'html' | 'js'): string {
  if (lang === 'ko') return source;
  let out = source;
  for (const key of KEYS_LONGEST_FIRST) {
    if (!out.includes(key)) continue;
    const value = EN[key] ?? key;
    out = out.split(key).join(context === 'html' ? escapeHtml(value) : escapeJs(value));
  }
  return out;
}
